"""Builds a test disk with a kernel and an initrd stored as RAW sectors
(no filesystem) and a matching BinBoot config.

usage: mkimage_linux.py KERNEL INITRD OUT.img OUT_config.c
"""
import struct
import sys

SECTOR = 512
kernel, initrd, out_img, out_cfg = sys.argv[1:5]
kdata, idata = open(kernel, "rb").read(), open(initrd, "rb").read()

def sectors(n):
    return (n + SECTOR - 1) // SECTOR

K_LBA = 8192
K_SEC = sectors(len(kdata))
I_LBA = (K_LBA + K_SEC + 2047) // 2048 * 2048
I_SEC = sectors(len(idata))
BAD_LBA = (I_LBA + I_SEC + 2047) // 2048 * 2048      # left zeroed on purpose
total = BAD_LBA + 4096

img = bytearray(total * SECTOR)
mbr = bytearray(SECTOR)
struct.pack_into("<I", mbr, 440, 0xB1B0B007)
# One small partition so the installer sees a normal MBR disk.
mbr[446:462] = struct.pack("<B3sB3sII", 0x80, b"\xfe\xff\xff", 0x83,
                           b"\xfe\xff\xff", 2048, 2048)
mbr[510:512] = b"\x55\xaa"
img[:SECTOR] = mbr
img[K_LBA * SECTOR:K_LBA * SECTOR + len(kdata)] = kdata
img[I_LBA * SECTOR:I_LBA * SECTOR + len(idata)] = idata
open(out_img, "wb").write(img)

open(out_cfg, "w").write(f'''/* Generated by mkimage_linux.py */
#include "binboot.h"

static const struct bb_extent kernel_ext[] = {{ {{ {K_LBA}, {K_SEC} }} }};
static const struct bb_extent initrd_ext[] = {{ {{ {I_LBA}, {I_SEC} }} }};
static const struct bb_extent bad_ext[]    = {{ {{ {BAD_LBA}, 64 }} }};

const struct bb_entry bb_entries[] = {{
    {{
        .name    = "Linux (raw sectors)",
        .cmdline = "console=ttyS0 rdinit=/init binboot=bios",
        .bios_linux = {{
            .enabled = 1, .drive = BB_BIOS_BOOT_DRIVE,
            .kernel = kernel_ext, .kernel_count = BB_COUNT(kernel_ext),
            .initrd = initrd_ext, .initrd_count = BB_COUNT(initrd_ext),
            .initrd_size = {len(idata)},
        }},
    }},
    {{
        .name    = "Bad kernel (zeros)",
        .bios_linux = {{
            .enabled = 1, .drive = BB_BIOS_BOOT_DRIVE,
            .kernel = bad_ext, .kernel_count = BB_COUNT(bad_ext),
        }},
    }},
}};

const size_t bb_entry_count = sizeof(bb_entries) / sizeof(bb_entries[0]);
''')
print(f"kernel LBA {K_LBA} x{K_SEC}, initrd LBA {I_LBA} x{I_SEC}")
